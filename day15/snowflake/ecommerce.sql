
SELECT
    CURRENT_USER() AS USER_NAME,
    CURRENT_ROLE() AS ACTIVE_ROLE,
    CURRENT_WAREHOUSE() AS ACTIVE_WAREHOUSE,
    CURRENT_DATABASE() AS ACTIVE_DATABASE,
    CURRENT_SCHEMA() AS ACTIVE_SCHEMA;


CREATE DATABASE IF NOT EXISTS ECOMMERCE_DB;

USE DATABASE ECOMMERCE_DB;

SHOW DATABASES LIKE 'ECOMMERCE_DB';



CREATE SCHEMA IF NOT EXISTS RAW;

USE SCHEMA ECOMMERCE_DB.RAW;

SHOW SCHEMAS IN DATABASE ECOMMERCE_DB;



CREATE WAREHOUSE IF NOT EXISTS ECOMMERCE_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

USE WAREHOUSE ECOMMERCE_WH;

SHOW WAREHOUSES LIKE 'ECOMMERCE_WH';

SELECT CURRENT_WAREHOUSE();



CREATE TABLE IF NOT EXISTS ECOMMERCE_DB.RAW.ORDERS (
    ORDER_ID VARCHAR(30),
    CUSTOMER_ID VARCHAR(30),
    CUSTOMER_NAME VARCHAR(255),
    EMAIL VARCHAR(255),
    ORDER_DATE DATE,
    PRODUCT_ID VARCHAR(30),
    CATEGORY VARCHAR(255),
    PRODUCT_NAME VARCHAR(255),
    QUANTITY NUMBER(12,2),
    UNIT_PRICE NUMBER(12,2),
    DISCOUNT_PCT NUMBER(5,2),
    SHIPPING_FEE NUMBER(12,2),
    PAYMENT_METHOD VARCHAR(100),
    ORDER_STATUS VARCHAR(100),
    CITY VARCHAR(100),
    STATE VARCHAR(100),
    POSTAL_CODE VARCHAR(20),
    TOTAL_AMOUNT NUMBER(14,2),
    CALCULATED_REVENUE NUMBER(14,2)
);



SHOW TABLES LIKE 'ORDERS'
IN SCHEMA ECOMMERCE_DB.RAW;

DESCRIBE TABLE ECOMMERCE_DB.RAW.ORDERS;



CREATE FILE FORMAT IF NOT EXISTS
ECOMMERCE_DB.RAW.ECOMMERCE_CSV_FORMAT
    TYPE = CSV
    FIELD_DELIMITER = ','
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE
    NULL_IF = ('NULL', 'null', '')
    DATE_FORMAT = 'YYYY-MM-DD'
    TRIM_SPACE = TRUE
    ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;



CREATE STAGE IF NOT EXISTS
ECOMMERCE_DB.RAW.ECOMMERCE_STAGE
    FILE_FORMAT =
    ECOMMERCE_DB.RAW.ECOMMERCE_CSV_FORMAT;

SHOW STAGES IN SCHEMA ECOMMERCE_DB.RAW;


LIST @ECOMMERCE_DB.RAW.ECOMMERCE_STAGE;



COPY INTO ECOMMERCE_DB.RAW.ORDERS
FROM @ECOMMERCE_DB.RAW.ECOMMERCE_STAGE
FILE_FORMAT = (
    FORMAT_NAME =
    'ECOMMERCE_DB.RAW.ECOMMERCE_CSV_FORMAT'
)
ON_ERROR = 'ABORT_STATEMENT'
VALIDATION_MODE = 'RETURN_ERRORS';



COPY INTO ECOMMERCE_DB.RAW.ORDERS
FROM @ECOMMERCE_DB.RAW.ECOMMERCE_STAGE
FILE_FORMAT = (
    FORMAT_NAME =
    'ECOMMERCE_DB.RAW.ECOMMERCE_CSV_FORMAT'
)
ON_ERROR = 'ABORT_STATEMENT';




SELECT *
FROM ECOMMERCE_DB.RAW.ORDERS
ORDER BY ORDER_ID
LIMIT 20;


SELECT COUNT(*) AS TOTAL_RECORDS
FROM ECOMMERCE_DB.RAW.ORDERS;


SELECT
    SUM(CALCULATED_REVENUE)
        AS TOTAL_REVENUE
FROM ECOMMERCE_DB.RAW.ORDERS;



SELECT
    CITY,
    SUM(CALCULATED_REVENUE)
        AS TOTAL_REVENUE
FROM ECOMMERCE_DB.RAW.ORDERS
GROUP BY CITY
ORDER BY TOTAL_REVENUE DESC;


SELECT
    ORDER_ID,
    ORDER_STATUS,
    TOTAL_AMOUNT,
    CALCULATED_REVENUE,
    ROUND(
        QUANTITY * UNIT_PRICE *
        (1 - COALESCE(DISCOUNT_PCT, 0) / 100)
        + COALESCE(SHIPPING_FEE, 0),
        2
    ) AS EXPECTED_TOTAL
FROM ECOMMERCE_DB.RAW.ORDERS
ORDER BY ORDER_ID;
