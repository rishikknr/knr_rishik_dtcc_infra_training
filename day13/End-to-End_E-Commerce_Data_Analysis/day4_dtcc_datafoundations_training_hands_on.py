import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from google.colab import drive

drive.mount('/content/drive')

file_path = "/content/drive/MyDrive/DTCC/training/data_foundations/data/cleaned_ecommerce.csv"

df = pd.read_csv(file_path)

df.head()

df.isna().sum()

df.info()

df.columns = df.columns.str.strip().str.lower()

df = df.drop_duplicates().copy()

print(df.shape)

numeric_cols = [
    'quantity', 'unit_price', 'discount_pct',
    'shipping_fee', 'total_amount'
]

for col in numeric_cols:
    df[col] = pd.to_numeric(
        df[col].astype('string').str.replace(
            r'₹|,|%|(?i:rupees?)', '', regex=True
        ).str.strip(),
        errors='coerce'
    )

print(df[numeric_cols].dtypes)

text_cols = [
    'customer_name', 'category', 'product_name',
    'payment_method', 'order_status', 'city', 'state'
]

for col in text_cols:
    df[col] = (
        df[col].astype('string')
        .str.strip()
        .str.replace(r'\s+', ' ', regex=True)
        .str.title()
    )

df['city'] = df['city'].replace({
    'Hyd': 'Hyderabad',
    'Chenn Ai': 'Chennai',
    'Bangalore': 'Bengaluru'
})

df['state'] = df['state'].replace({
    'Tn': 'Tamil Nadu',
    'Ts': 'Telangana',
    'Ka': 'Karnataka',
    'Mh': 'Maharashtra'
})

print(df['city'].value_counts())

df = df.replace(
    ['Not Available', 'N/A', 'NA', 'null', ''],
    pd.NA
)

print(df.isnull().sum())

df['customer_name'] = df['customer_name'].fillna('Unknown')
df['email'] = df['email'].fillna('Not Available')
df['payment_method'] = df['payment_method'].fillna('Unknown')

df['order_date'] = pd.to_datetime(
    df['order_date'], errors='coerce'
)

df['day'] = df['order_date'].dt.day
df['month'] = df['order_date'].dt.month
df['year'] = df['order_date'].dt.year

df['month_name'] = df['order_date'].dt.month_name()

df['month_year'] = df['order_date'].dt.to_period('M')

df[['order_date', 'day', 'month',
    'month_name', 'year', 'month_year']].head()

df['calculated_revenue'] = (
    df['quantity'] * df['unit_price']
    * (1 - df['discount_pct'] / 100)
    + df['shipping_fee']
).round(2)

df['revenue_difference'] = (
    df['total_amount'] - df['calculated_revenue']
).round(2)

mismatches = df[
    df['revenue_difference'].abs() > 0.01
]

print(mismatches[
    ['order_id', 'total_amount',
     'calculated_revenue', 'revenue_difference']
])

df.describe()

df.shape

df.duplicated().sum()

df['order_id'].nunique()

df.info()

df.head()

df.columns

df['total_amount'] = df['total_amount'].fillna(
    df['calculated_revenue']
)

monthly_revenue = (
    df.dropna(subset=['month_year', 'calculated_revenue'])
    .groupby('month_year')['calculated_revenue']
    .sum()
    .reset_index()
    .sort_values('month_year')
)

monthly_revenue['month_year'] = (
    monthly_revenue['month_year'].astype(str)
)

monthly_revenue

plt.figure(figsize=(10, 5))

plt.bar(
    monthly_revenue['month_year'],
    monthly_revenue['calculated_revenue'],
    color='skyblue'
)

plt.title('Monthly Revenue Distribution')
plt.xlabel('Month')
plt.ylabel('Total Revenue (₹)')
plt.xticks(rotation=45)
plt.grid(axis='y', alpha=0.3)
plt.tight_layout()
plt.show()

plt.figure(figsize=(10, 5))

plt.plot(
    monthly_revenue['month_year'].astype(str),
    monthly_revenue['calculated_revenue'],
    color='skyblue',
    marker='o',
    linestyle='-',
    linewidth=2
)

plt.title('Monthly Revenue Distribution')
plt.xlabel('Month')
plt.ylabel('Total Revenue (₹)')
plt.xticks(rotation=45)
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

region_revenue = (
    df.groupby('state')['calculated_revenue']
    .sum()
    .reset_index()
    .sort_values('calculated_revenue', ascending=False)
)

region_revenue

plt.figure(figsize=(10, 5))

plt.bar(
    region_revenue['state'],
    region_revenue['calculated_revenue'],
    color='skyblue'
)

plt.title('Revenue by Region')
plt.xlabel('State')
plt.ylabel('Total Revenue (₹)')
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()

product_revenue = (
    df.groupby('product_name')['calculated_revenue']
    .sum()
    .sort_values(ascending=False)
)

product_revenue

plt.figure(figsize=(10, 6))

plt.barh(
    product_revenue.index,
    product_revenue.values,
    color='green'
)

plt.title('Revenue by Product')
plt.xlabel('Total Revenue (₹)')
plt.ylabel('Product')
plt.gca().invert_yaxis()
plt.grid(axis='x', alpha=0.3)
plt.tight_layout()
