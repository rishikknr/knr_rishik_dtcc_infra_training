SELECT 'CUSTOMERS' AS TABLE_NAME, COUNT(*) AS RECORDS
FROM ECOMMERCE_DB.CLEAN.CUSTOMERS
UNION ALL
SELECT 'PRODUCTS', COUNT(*)
FROM ECOMMERCE_DB.CLEAN.PRODUCTS
